#!/usr/bin/env python3
"""
gen_font.py — emit a compact 5x7 bitmap font as a C initializer for ui_oled.

Covers ASCII 0x20 (space) through 0x5A ('Z'): space, the symbols the UI uses,
digits, and uppercase letters. Lowercase is rendered by up-casing in the driver,
so it is intentionally not stored. Glyphs are authored here as ASCII art ('#' =
lit pixel) so they are human-verifiable:

  python3 tools/gen_font.py --preview     # render every glyph back as ASCII art
  python3 tools/gen_font.py > firmware/components/ui_oled/font5x7.inc

Encoding in the .inc: 5 bytes per glyph, one byte per column (x = 0..4); within a
byte, bit y (0 = top) is row y (0..6).
"""
import sys

FIRST = 0x20
LAST = 0x5A
W, H = 5, 7

# Each glyph: 7 rows of 5 chars. Missing entries render blank.
