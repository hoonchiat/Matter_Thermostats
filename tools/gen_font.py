def glyph_columns(art):
    """Return 5 column bytes for a 7-row x 5-col art block."""
    cols = [0] * W
    for y in range(H):
        row = art[y] if y < len(art) else "     "
        for x in range(W):
            if x < len(row) and row[x] == '#':
                cols[x] |= (1 << y)
    return cols


def preview():
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        cols = glyph_columns(G.get(ch, ["     "] * 7))
        print(f"0x{code:02X} '{ch}'")
        for y in range(H):
            print("  " + "".join('#' if (cols[x] >> y) & 1 else '.' for x in range(W)))
        print()


def emit_c():
    print("/* Auto-generated by tools/gen_font.py — do not edit by hand. */")
    print("/* 5x7 font, ASCII 0x20..0x5A. 5 bytes/glyph, column-major, bit0=top row. */")
    print(f"#define FONT5X7_FIRST 0x{FIRST:02X}")
    print(f"#define FONT5X7_LAST  0x{LAST:02X}")
    print("static const uint8_t font5x7[][5] = {")
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        cols = glyph_columns(G.get(ch, ["     "] * 7))
        label = ch if ch != '\\' else '\\\\'
        print("    { " + ", ".join(f"0x{c:02X}" for c in cols) + f" }},  /* '{label}' */")
    print("};")


if __name__ == "__main__":
    if "--preview" in sys.argv:
        preview()
    else:
        emit_c()
